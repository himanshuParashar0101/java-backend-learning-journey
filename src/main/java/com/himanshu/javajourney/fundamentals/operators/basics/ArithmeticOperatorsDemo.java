package com.himanshu.javajourney.fundamentals.operators.basics;

public class ArithmeticOperatorsDemo {

    public static void main(String[] args) {
        int firstNumber = 15;
        int secondNumber = 4;

        System.out.println(firstNumber + secondNumber);
        System.out.println(firstNumber - secondNumber);
        System.out.println(firstNumber * secondNumber);
        System.out.println(firstNumber / secondNumber);
        System.out.println(firstNumber % secondNumber);
    }
}